"""Script to programmatically generate evidence/FINAL_REPORT.md from evidence/gates/g*.json.

Enforces Rule R1 and R2:
- No hand-edited text or fabricated numbers.
- Dynamic aggregation from verified gate JSON artifacts.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Any

PROJECT_ROOT = Path(__file__).resolve().parents[1]
GATES_DIR = PROJECT_ROOT / "evidence" / "gates"
OUTPUT_FILE = PROJECT_ROOT / "evidence" / "FINAL_REPORT.md"

GATE_NAMES = {
    "G00": "Hygiene & Suppressions",
    "G01": "Anti-Gaming & Zero-Seed",
    "G02": "Mutation Canary",
    "G03": "Security & Tamper Suite",
    "G04": "Protocol Authentication",
    "G05": "GeoIP & OSINT Intelligence",
    "G06": "Header Forensics & Fuzzing",
    "G07": "AI Intent Classification",
    "G08": "Threat Campaigns & STIX 2.1",
    "G09": "Section 63 BSA 2023 Reporting",
    "G10": "Architecture & Disaster Recovery",
    "G11": "Frontend Completeness & Build",
    "G12": "Test Suite Pass & Coverage",
    "G13": "Empirical Performance",
    "G14": "Continuous Integration",
    "G15": "Docs & Metric Traceability",
}


def load_all_gates() -> Dict[str, Dict[str, Any]]:
    gates = {}
    for i in range(16):
        g_id = f"G{i:02d}"
        f_name = GATES_DIR / f"g{i:02d}.json"
        if f_name.exists():
            try:
                gates[g_id] = json.loads(f_name.read_text(encoding="utf-8"))
            except Exception as e:
                gates[g_id] = {"status": "ERROR", "error": str(e)}
        else:
            gates[g_id] = {"status": "MISSING"}
    return gates


def generate_report() -> str:
    gates = load_all_gates()
    pass_count = sum(1 for g in gates.values() if g.get("status") == "PASS")
    blocked_count = sum(1 for g in gates.values() if g.get("status") == "BLOCKED")
    fail_count = sum(1 for g in gates.values() if g.get("status") in ("FAIL", "ERROR", "MISSING"))
    total_count = len(gates)

