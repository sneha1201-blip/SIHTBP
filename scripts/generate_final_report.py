        "- **Empirical AI Evaluation (N=2,872):** Multi-class Platt-calibrated classifier: Holdout Accuracy **94.26%**, ROC-AUC **0.9660**, ECE **0.0334** (95% CI: [0.0269, 0.0528]). Two-tier architecture maps 4-class calibrated NLP model deterministically to official PS 26106 5-class court-admissible verdicts.",
